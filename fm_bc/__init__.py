"""Flow-matching-style BC on SE(2) robots, with divergence/score estimators, for two tasks.

The package root holds what the tasks share; each task has a subpackage of its own:

``fm_bc.skate``
    Skate-robot navigation: demonstrations generated by the Theseus planner through the three
    Fig. 6 obstacle scenarios. Needs Theseus, through :mod:`skate_planner`.
``fm_bc.pusht``
    Push-T manipulation from human demonstrations. Torch only.
``fm_bc.se2``, ``fm_bc.divergence``, ``fm_bc.windows``, ``fm_bc.benchmarks``, ``fm_bc.nets``
    Shared by both: batched SE(2) log / exp, kNN / KDE divergence and the kernel score,
    chunk-window indices, synthetic flows of known divergence, and the ported network backbones.

Quick start::

    from fm_bc import divergence_knn, score_kernel
    from fm_bc.skate import get_scenario, generate

Submodules are imported **lazily** (PEP 562), so importing the root never pulls in Theseus: the
shared modules and the whole of ``fm_bc.pusht`` import on a machine that has torch but no
``theseus`` / ``skate_planner`` -- which is what lets the Push-T data pipeline and its tests run
anywhere.
"""

from __future__ import annotations

import importlib

# Public name -> the submodule that defines it.
_EXPORTS = {
    "divergence_kde": ".divergence",
    "divergence_knn": ".divergence",
    "log_density_kde": ".divergence",
    "manifold_dim": ".divergence",
    "score_kernel": ".divergence",
    "state_distances": ".divergence",
    "pairwise_twists": ".se2",
    "se2_exp_retract": ".se2",
    "se2_log": ".se2",
    "twist_norm": ".se2",
    "wrap_angle": ".se2",
    "episode_window_indices": ".windows",
    "window_indices": ".windows",
}

__all__ = [
    "divergence_knn",
    "score_kernel",
    "state_distances",
    "manifold_dim",
    "se2_log",
    "se2_exp_retract",
    "pairwise_twists",
    "twist_norm",
    "window_indices",
    "episode_window_indices",
]


def __getattr__(name: str):
    """Resolve a public name to its submodule on first access, then cache it in ``globals()``."""
    if name not in _EXPORTS:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    module = importlib.import_module(_EXPORTS[name], __name__)
    globals()[name] = value = getattr(module, name)
    return value


def __dir__() -> list[str]:
    return sorted(set(globals()) | set(_EXPORTS))
